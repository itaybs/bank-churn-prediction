"""Write outputs/report.md from the results of the current run.

Every number in the report is read from the objects passed in (the actual
run), never typed by hand. Comparative sentences are generated by
churn.insights from those numbers, so the wording stays correct if the
results change.
"""

from pathlib import Path

import numpy as np
import pandas as pd

from churn import config
from churn.formatting import fmt3, fmt3_signed
from churn.insights import (
    GAP_STD_RULE,
    analytical_summary,
    best_model,
    generalisation_notes,
    generalisation_table,
    importance_insights,
    segment_stats,
)
from churn.models import CATBOOST_PARAMS, FOREST_PARAMS, LIGHTGBM_PARAMS, LOGISTIC_PARAMS, XGBOOST_PARAMS
from churn.tuning import COMPARISON_STAGES, TUNING_METRIC, tuning_insights
from churn.validation import format_mean_std


def _cell(value, col: str = "") -> str:
    """Every number goes through the project's single rounding rule (churn.formatting)."""
    if isinstance(value, (bool, np.bool_)):
        return "✅ yes" if value else "⚠️ no"
    if isinstance(value, str):
        return value
    if isinstance(value, (int, np.integer)):
        return f"{value:,}"
    return fmt3_signed(value) if "−" in col else fmt3(value)


def _markdown_table(table: pd.DataFrame, index_name: str = "Model") -> str:
    headers = [index_name] + list(table.columns)
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for idx, row in table.iterrows():
        lines.append("| " + " | ".join([str(idx)] + [_cell(v, c) for c, v in row.items()]) + " |")
    return "\n".join(lines)


def _distribution_line(dist: pd.DataFrame) -> str:
    return ", ".join(
        f"`Exited={cls}`: {int(r['count']):,} ({r['percent']:.2f}%)" for cls, r in dist.iterrows()
    )


def _params(params: dict) -> str:
    hidden = {"n_jobs", "thread_count", "verbose", "allow_writing_files"}
    return ", ".join(f"`{k}={v!r}`" for k, v in params.items() if k not in hidden)


def _tuning_section(tuning: dict | None) -> list[str]:
    if tuning is None:
        return ["Tuning was not run."]
    comparison, params = tuning["comparison"], tuning["params"]
    insights = tuning_insights(comparison, tuning["baseline_folds"], tuning["tuned_folds"], params,
                               tuning["cv_candidates"], tuning["test_candidates"])
    rows = []
    for (model, metric), group in comparison.groupby(["Model", "Metric"], sort=False):
        by_stage = group.set_index("Stage")
        rows.append({
            "Model": model, "Metric": metric.replace("_", "-"),
            **{f"{stage}: {v}": by_stage.loc[stage, v] for stage in COMPARISON_STAGES for v in ["Baseline", "Tuned"]},
            **{f"{stage}: tuned − baseline": by_stage.loc[stage, "Change"] for stage in COMPARISON_STAGES},
        })
    table = pd.DataFrame(rows).set_index("Model")
    shown_params = params.assign(Changed=params["Changed"].map({True: "yes", False: "no"})).set_index("Model")
    cv_c, test_c = tuning["cv_candidates"], tuning["test_candidates"]
    candidates = pd.DataFrame({
        "CV ROC-AUC mean": cv_c["ROC_AUC mean"], "CV ROC-AUC std": cv_c["ROC_AUC std"],
        **{f"Test {m.replace('_', '-')}": test_c[m] for m in ["Precision", "Recall", "F1", "ROC_AUC"]},
    })
    return [
        f"Random Forest and XGBoost were tuned with `GridSearchCV`, scored by {TUNING_METRIC.replace('_', '-')} in "
        f"{config.CV_FOLDS}-fold stratified cross-validation on the **training set only**, using the same folds as "
        "the baseline cross-validation. Each grid includes the baseline settings. The best candidate was refitted "
        "on the full training set, saved to `outputs/models/`, and evaluated once on the test set.",
        "",
        "**Hyperparameters searched**",
        "",
        _markdown_table(shown_params),
        "",
        "**Before vs after tuning** (CV = mean of the folds; Test = untouched test set, threshold 0.5)",
        "",
        _markdown_table(table),
        "",
        "![Before vs after tuning](tuning_before_after.png)",
        "",
        "**All candidates** (baseline models and tuned versions)",
        "",
        _markdown_table(candidates),
        "",
        "**What tuning changed (measured):**",
        "",
        *[f"- {line}" for line in insights["per_model"]],
        "",
        "**Best model overall (measured):**",
        "",
        *[f"- {line}" for line in insights["best"]],
        "",
        "**Trade-offs between Precision, Recall and ROC-AUC (measured):**",
        "",
        *[f"- {line}" for line in insights["tradeoffs"]],
        "",
        "**Caveats:**",
        "",
        *[f"- {line}" for line in insights["caveats"]],
        "",
        "Full grid results are in `outputs/tuning_grid_results.csv`.",
    ]


def _segment_table(X_train: pd.DataFrame, y_train: pd.Series, feature: str) -> pd.DataFrame:
    stats = segment_stats(X_train, y_train, feature)
    return pd.DataFrame({
        "Customers (n)": stats["n"].astype(int).map("{:,}".format),
        "Churned": stats["churned"].astype(int).map("{:,}".format),
        "Churn rate": stats["rate"].map("{:.1%}".format),
        "Sample size": stats["small"].map({True: "⚠️ small (n < 100)", False: "ok"}),
    })


def _conclusion(table: pd.DataFrame, cv_summary: pd.DataFrame) -> list[str]:
    best = best_model(cv_summary)  # selection uses cross-validation on the training set only
    confirmed = table["ROC_AUC"].idxmax() == best
    key = ["Recall", "Precision", "F1", "ROC_AUC"]
    dominant = all(table.loc[best, k] >= table[k].max() for k in key)
    if confirmed and dominant:
        first = (
            f"**{best}** is selected: it has the highest mean ROC-AUC in cross-validation on the training set. "
            f"The untouched test set confirms the choice: there it also scored at least as well as every "
            f"alternative on Recall, Precision, F1 (for `Exited=1`) and ROC-AUC."
        )
    elif confirmed:
        first = (
            f"**{best}** is selected (highest mean ROC-AUC in cross-validation), and the test set confirms that it "
            f"ranks customers best, but it does not lead on every threshold-dependent metric. The final choice "
            f"depends on the relative cost of missed churners and false alarms."
        )
    else:
        first = (
            f"**{best}** is selected (highest mean ROC-AUC in cross-validation), but the untouched test set does "
            f"not confirm it ({table['ROC_AUC'].idxmax()} has the higher test ROC-AUC). The selection is not changed "
            f"after looking at the test set; the evidence is insufficient to name a definitive winner."
        )
    return [
        first,
        "",
        f"At the default 0.5 threshold the best Recall was {fmt3(table['Recall'].max())}, so many churners are "
        f"still missed. If identifying churners is the priority, the decision threshold should be chosen with "
        f"cross-validation on the training data (as the dashboard's *CV-optimized* strategy does) and confirmed "
        f"on new data. No model should be treated as ready for real-world banking decisions without further "
        f"validation.",
    ]


def write_report(
    path: Path,
    dataset_name: str,
    n_rows: int,
    n_columns: int,
    distribution: pd.DataFrame,
    train_distribution: pd.DataFrame,
    test_distribution: pd.DataFrame,
    table: pd.DataFrame,
    train_table: pd.DataFrame,
    matrices: dict[str, np.ndarray],
    cv_summary: pd.DataFrame,
    cv_folds: dict[str, pd.DataFrame],
    builtin: pd.DataFrame,
    permutation: dict[str, pd.DataFrame],
    X_train: pd.DataFrame,
    y_train: pd.Series,
    output_files: list[Path],
    tuning: dict | None = None,
) -> Path:
    n_train = int(train_distribution["count"].sum())
    n_test = int(test_distribution["count"].sum())
    majority_rate = test_distribution["percent"].max() / 100
    summary = analytical_summary(table, cv_summary, cv_folds, X_train, y_train, permutation)
    model_list = ", ".join(table.index[:-1]) + f" and {table.index[-1]}"

    cm_lines = []
    for name, cm in matrices.items():
        tn, fp, fn, tp = cm.ravel()
        cm_lines.append(
            f"- **{name}:** TN = {tn}, FP = {fp}, FN = {fn}, TP = {tp}. It correctly identified "
            f"{tp} of {tp + fn} churners and missed {fn}; {fp} of {tn + fp} customers who stayed "
            f"were wrongly flagged as churners."
        )

    gap = generalisation_table(cv_summary, table, train_table, "ROC_AUC")
    importance = builtin.add_suffix(" (built-in)")
    for name, perm in permutation.items():
        importance[f"{name} (permutation)"] = perm["importance_mean"]
    importance = importance.sort_values(importance.columns[-1], ascending=False)

    if tuning is not None:
        tuning = {**tuning, "baseline_folds": cv_folds}
    sections = [
        "# Bank Customer Churn Prediction: Results Report",
        "",
        "_All numbers in this report were produced by `python main.py` on "
        f"`{dataset_name}` and match the CSV files in `outputs/`._",
        "",
        "## 1. Project objective",
        "",
        f"Predict whether a bank customer will leave the bank (`Exited = 1`) and compare {len(table)} "
        f"classifiers, {model_list}, on the same data split.",
        "",
        "## 2. Dataset overview",
        "",
        f"- **Size:** {n_rows:,} rows, {n_columns} columns. No missing values in the features "
        "(checked during validation).",
        f"- **Target:** `{config.TARGET}` (1 = customer left, 0 = customer stayed).",
        f"- **Class distribution:** {_distribution_line(distribution)}. The classes are imbalanced.",
        f"- **Features used ({len(config.FEATURES)}):** numeric: "
        + ", ".join(f"`{c}`" for c in config.NUMERIC_FEATURES)
        + "; categorical: "
        + ", ".join(f"`{c}`" for c in config.CATEGORICAL_FEATURES)
        + ".",
        "",
        "## 3. Data preparation",
        "",
        f"- **Excluded columns:** {', '.join(f'`{c}`' for c in config.ID_COLUMNS)}. These are "
        "identifiers with no general relationship to churn and could let a model memorise "
        "individuals. They are dropped from the features only; the CSV is not modified. "
        f"`{config.TARGET}` is the target and is never a feature.",
        "- **Categorical encoding:** `Geography` and `Gender` are one-hot encoded with "
        "`OneHotEncoder(handle_unknown=\"ignore\")`.",
        "- **Scaling:** numeric features are standardised (`StandardScaler`) for Logistic "
        "Regression only. The tree models use unscaled values because tree splits do not depend on scale.",
        f"- **Train/test split:** one shared stratified split: {n_train:,} training rows "
        f"({1 - config.TEST_SIZE:.0%}) and {n_test:,} test rows ({config.TEST_SIZE:.0%}), "
        f"`random_state={config.RANDOM_STATE}`. Train: {_distribution_line(train_distribution)}. "
        f"Test: {_distribution_line(test_distribution)}.",
        "- **Leakage prevention:** the split happens first. Encoders and scalers sit inside each "
        "model's `Pipeline`, so they are fitted only on training rows, both in the final fit and "
        "inside every cross-validation fold.",
        "",
        "## 4. Models",
        "",
        "The main comparison uses documented baseline hyperparameters. Random Forest and XGBoost are "
        "additionally tuned with GridSearchCV in Section 7; the baselines are kept so the effect of tuning is visible.",
        "",
        f"- **Logistic Regression** ({_params(LOGISTIC_PARAMS)}, default L2 regularisation, C = 1.0): a "
        "linear model of the log-odds of churn. It is simple and interpretable, but it can only represent "
        "effects that are linear in the log-odds unless features are engineered.",
        f"- **Random Forest** ({_params(FOREST_PARAMS)}): **bagging**. Many deep decision trees are each "
        "trained on a bootstrap sample with random feature subsets, and their predictions are averaged.",
        f"- **XGBoost** ({_params(XGBOOST_PARAMS)}): **gradient boosting**. Shallow trees are added one at a "
        "time, each fitted to the errors of the trees before it, with shrinkage, subsampling and an L2 "
        "penalty as regularisation.",
        f"- **LightGBM** ({_params(LIGHTGBM_PARAMS)}): gradient boosting with histogram-based splits and "
        "**leaf-wise** tree growth (it expands the leaf with the largest loss reduction), capped by `num_leaves`.",
        f"- **CatBoost** ({_params(CATBOOST_PARAMS)}): gradient boosting with **symmetric (oblivious) trees** "
        "(the same split at every node of a level) and ordered boosting to reduce overfitting. Here it receives "
        "the same one-hot-encoded input as the other models.",
        "",
        "## 5. Evaluation methodology",
        "",
        f"- **Cross-validation:** {config.CV_FOLDS}-fold stratified k-fold on the **training set only**. Each "
        "fold is held out once while a fresh pipeline is fitted on the other folds. All models use the same "
        "folds, so their fold scores can be compared pairwise. The mean estimates performance on unseen "
        "data; the standard deviation shows its stability.",
        "- **Test set:** each model is then refitted on the full training set and evaluated once on the "
        f"untouched {n_test:,}-row test set.",
        "- All metrics use `Exited = 1` as the positive class. Class labels use the default 0.5 threshold.",
        "- **Precision:** of the customers predicted to churn, the share who actually churned.",
        "- **Recall:** of the customers who actually churned, the share the model identified.",
        "- **F1-score:** harmonic mean of Precision and Recall.",
        "- **Accuracy:** share of all predictions that were correct. It is a supplementary metric "
        "only, because always predicting \"stayed\" would already score "
        f"{majority_rate:.3f} on this test set.",
        "- **ROC-AUC:** the probability that a random churner gets a higher score than a random non-churner "
        "(0.5 = random, 1.0 = perfect); independent of the threshold.",
        "",
        "## 6. Results",
        "",
        f"### Cross-validation on the training set ({config.CV_FOLDS} folds, mean ± std)",
        "",
        _markdown_table(format_mean_std(cv_summary)),
        "",
        "Per-fold scores are in `outputs/cv_folds.csv`.",
        "",
        f"### Test set (n = {n_test:,})",
        "",
        _markdown_table(table),
        "",
        "### Generalisation check (ROC-AUC: training data vs cross-validation vs test)",
        "",
        _markdown_table(gap),
        "",
        f"*Train* is each final model scored on its own 8,000 training customers. *Test within {GAP_STD_RULE} CV "
        f"std* checks whether the test score lies within {GAP_STD_RULE} standard deviations of the CV mean.",
        "",
        *[f"- {line}" for line in generalisation_notes(gap)],
        "",
        "### Churn rate by segment, with sample sizes (training set)",
        "",
        "Segments with fewer than 100 customers are flagged: their rates are unstable.",
        "",
        "**`NumOfProducts`**",
        "",
        _markdown_table(_segment_table(X_train, y_train, "NumOfProducts"), "NumOfProducts"),
        "",
        "**`Age` band**",
        "",
        _markdown_table(_segment_table(X_train, y_train, "Age"), "Age"),
        "",
        "### Confusion matrices (test set)",
        "",
        *cm_lines,
        "",
        "![Confusion matrices](confusion_matrices.png)",
        "",
        "### ROC curves (test set)",
        "",
        "![ROC curves](roc_curves.png)",
        "",
        "## 7. Hyperparameter tuning (before vs after)",
        "",
        *_tuning_section(tuning),
        "",
        "## 8. Feature importance",
        "",
        "- **Built-in** (tree models): Random Forest = mean decrease in impurity; XGBoost = average gain; "
        "LightGBM = total gain; CatBoost = PredictionValuesChange (how much the prediction changes, on average, "
        "when the feature's value changes). All are computed during training and normalised to sum to 1.",
        "- **Permutation** (all models): drop in test ROC-AUC when one feature is randomly shuffled "
        "(10 repeats). One-hot columns are summed back to `Geography` and `Gender`.",
        "",
        _markdown_table(importance, "Feature"),
        "",
        *[f"- {line}" for line in importance_insights(builtin, permutation)],
        "",
        "![Feature importance](feature_importance.png)",
        "",
        "## 9. Comparison and interpretation",
        "",
        "**Verdict (measured):**",
        "",
        *[f"- {line}" for line in summary["verdict"]],
        "",
        "**Robustness across cross-validation folds (measured):**",
        "",
        *[f"- {line}" for line in summary["evidence"]],
        "",
        "**Why (measured patterns, then explanations of the algorithms):**",
        "",
        *[f"- {line}" for line in summary["why"]],
        "",
        "## 10. Limitations",
        "",
        *[f"- {line}" for line in summary["caveats"]],
        "- The 0.5 threshold is a default, not a business-informed choice. The real costs of missed "
        "churners versus false alarms are unknown.",
        "- The dataset is a single static snapshot, and its origin and time period are not documented "
        "here. Patterns may not transfer to other banks or periods.",
        "",
        "## 11. Conclusion",
        "",
        *_conclusion(table, cv_summary),
        "",
        "## Generated output files",
        "",
        *[f"- `outputs/{p.name}`" for p in output_files],
        "",
    ]
    path.write_text("\n".join(sections), encoding="utf-8")
    return path
